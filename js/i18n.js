(function(){
  "use strict";
  var STORAGE_KEY = "ssk-lang";

  function translate(lang, key){
    var dict = window.SSK_I18N[lang] || window.SSK_I18N.en;
    if (key in dict) return dict[key];
    return window.SSK_I18N.en[key] || "";
  }

  // Missing key (e.g. a cached older i18n.js) keeps the text already in the
  // markup instead of blanking the element.
  function fill(el, key, read, write){
    var store = "_sskDefault_" + (read === null ? "text" : read);
    if (!(store in el)) el[store] = read === null ? el.textContent : (el.getAttribute(read) || "");
    write(translate(document.documentElement.getAttribute("lang"), key) || el[store]);
  }

  function applyLanguage(lang){
    if (!window.SSK_I18N[lang]) lang = "en";
    document.documentElement.setAttribute("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach(function(el){
      fill(el, el.getAttribute("data-i18n"), null, function(v){ el.textContent = v; });
    });
    [["data-i18n-placeholder", "placeholder"], ["data-i18n-aria", "aria-label"], ["data-i18n-alt", "alt"]].forEach(function(pair){
      document.querySelectorAll("[" + pair[0] + "]").forEach(function(el){
        fill(el, el.getAttribute(pair[0]), pair[1], function(v){ el.setAttribute(pair[1], v); });
      });
    });
    document.querySelectorAll(".lang-current").forEach(function(el){
      el.textContent = lang.toUpperCase();
    });
    document.querySelectorAll(".lang-option").forEach(function(el){
      el.classList.toggle("lang-active", el.getAttribute("data-lang") === lang);
    });

    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  function getInitialLanguage(){
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved && window.SSK_I18N[saved]) return saved;
    } catch (e) {}
    return "en";
  }

  document.addEventListener("click", function(e){
    var opt = e.target.closest(".lang-option");
    if (!opt) return;
    applyLanguage(opt.getAttribute("data-lang"));
    var menu = opt.closest(".lang-switch");
    if (menu) menu.classList.remove("open");
  });

  window.SSK_setLanguage = applyLanguage;
  window.SSK_t = function(key){
    return translate(document.documentElement.getAttribute("lang") || "en", key);
  };
  applyLanguage(getInitialLanguage());
})();
