(function(){
  "use strict";
  var STORAGE_KEY = "ssk-lang";

  function translate(lang, key){
    var dict = window.SSK_I18N[lang] || window.SSK_I18N.en;
    if (key in dict) return dict[key];
    return window.SSK_I18N.en[key] || "";
  }

  function applyLanguage(lang){
    if (!window.SSK_I18N[lang]) lang = "en";
    document.documentElement.setAttribute("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach(function(el){
      el.textContent = translate(lang, el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function(el){
      el.setAttribute("placeholder", translate(lang, el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function(el){
      el.setAttribute("aria-label", translate(lang, el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll(".lang-current").forEach(function(el){
      el.textContent = lang.toUpperCase();
    });
    document.querySelectorAll(".lang-option").forEach(function(el){
      el.classList.toggle("lang-active", el.getAttribute("data-lang") === lang);
    });

    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  function getInitialLanguage(){
    try {
      var saved = localStorage.getItem(STORAGE_KEY);
      if (saved && window.SSK_I18N[saved]) return saved;
    } catch (e) {}
    return "en";
  }

  document.addEventListener("click", function(e){
    var opt = e.target.closest(".lang-option");
    if (!opt) return;
    applyLanguage(opt.getAttribute("data-lang"));
    var menu = opt.closest(".lang-switch");
    if (menu) menu.classList.remove("open");
  });

  window.SSK_setLanguage = applyLanguage;
  applyLanguage(getInitialLanguage());
})();
